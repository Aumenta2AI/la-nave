import {test,expect} from '@playwright/test';
test('Nave real: 102 modelos, órbita, zoom, selección y móvil',async({page})=>{
  const models=new Set<string>();page.on('response',r=>{if(r.ok()&&/\/models\/areas\/.*\.glb$/.test(r.url()))models.add(r.url());});
  await page.goto('/');
  const canvas=page.locator('canvas[data-models="102"]');
  await expect(canvas).toBeVisible({timeout:30000});
  expect(models.size).toBe(6);
  await page.getByRole('button',{name:'Pantalla completa',exact:true}).click();
  await expect.poll(()=>page.evaluate(()=>document.fullscreenElement?.classList.contains('ship-layout'))).toBe(true);
  await expect.poll(async()=>Math.round((await canvas.boundingBox())!.height)).toBe(page.viewportSize()!.height);
  await page.getByRole('button',{name:'Salir de pantalla completa',exact:true}).click();
  await expect.poll(()=>page.evaluate(()=>document.fullscreenElement===null)).toBe(true);
  await page.getByRole('button',{name:'Cerrar cúpula',exact:true}).click();
  await expect(canvas).toHaveAttribute('data-dome','closed');
  await page.getByRole('button',{name:'Abrir nave',exact:true}).click();
  await expect(canvas).toHaveAttribute('data-dome','open');
  await expect(page.getByRole('button',{name:'Licitaciones Públicas · 7',exact:true})).toHaveCount(1);
  await expect(page.getByRole('button',{name:'ISO y Calidad · 7',exact:true})).toHaveCount(1);
  await expect(page.getByRole('button',{name:'Ciberseguridad · 7',exact:true})).toHaveCount(1);
  await expect(page.getByLabel('Puesto seleccionado',{exact:true})).toHaveCount(0);
  const before=await canvas.getAttribute('data-camera');
  const rect=(await canvas.boundingBox())!;
  await page.mouse.move(rect.x+rect.width*.45,rect.y+rect.height*.5);
  await page.mouse.down();await page.mouse.move(rect.x+rect.width*.6,rect.y+rect.height*.55,{steps:10});await page.mouse.up();
  await expect(canvas).not.toHaveAttribute('data-camera',before!);
  await page.getByRole('button',{name:'Donna · Coordinación',exact:true}).click();
  await expect(page.getByLabel('Puesto seleccionado',{exact:true})).toContainText('Donna');
  await expect(page.getByRole('button',{name:'Abrir conversación ↗'})).toBeVisible();
  await page.getByRole('button',{name:'Cerrar puesto seleccionado'}).click();
  await page.setViewportSize({width:390,height:898});
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Vista satelital',exact:true}).click();
  await expect(canvas).toHaveAttribute('data-crew','102');
});
