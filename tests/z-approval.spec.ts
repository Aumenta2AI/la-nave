import { test, expect } from '@playwright/test';
test('El puente bloquea escritura no aprobada, cambios y reintentos inciertos; falla sin avanzar cursor', async ({ page, request }) => {
    const state = async () => (await request.get('/api/state')).json();
    const agent = await (await request.post('/api/agents', { data: { name: 'Auditor de pruebas', personality: 'Riguroso', objective: 'Verificar permisos', specialty: 'Auditoría', done: 'Evidencia', appearance: 'Hittan', effort: 'medium', fallback: false } })).json();
    const effects = async () => (await (await request.get('/api/test/effects')).json()).length;
    const baseline = await effects();
    const send = async (text: string) => request.post('/api/agents/' + agent.id + '/messages', { data: { text } });
    await send('intenta enviar sin aprobación');
    await expect.poll(async () => (await state()).agents.find((a: any) => a.id === agent.id).state).toBe('error');
    expect(await effects()).toBe(baseline);
    await send('prepara correo');
    await expect.poll(async () => (await state()).requests.filter((r: any) => r.agentId === agent.id && r.status === 'pending').length).toBe(1);
    let r = (await state()).requests.find((r: any) => r.agentId === agent.id && r.status === 'pending');
    await request.post('/api/requests/' + r.id + '/decision', { data: { decision: 'changes', response: 'Cambia el asunto' } });
    await request.post('/api/requests/' + r.id + '/decision', { data: { decision: 'approve' } });
    expect(await effects()).toBe(baseline);
    await send('correo incierto');
    await expect.poll(async () => (await state()).requests.filter((r: any) => r.agentId === agent.id && r.status === 'pending').length).toBe(1);
    r = (await state()).requests.find((r: any) => r.agentId === agent.id && r.status === 'pending');
    await request.post('/api/requests/' + r.id + '/decision', { data: { decision: 'approve' } });
    expect((await state()).requests.find((x: any) => x.id === r.id).status).toBe('uncertain');
    await request.post('/api/requests/' + r.id + '/decision', { data: { decision: 'approve' } });
    expect(await effects()).toBe(baseline + 1);
    await page.goto('/');
    await page.getByRole('button', { name: 'Solicitudes', exact: false }).click();
    await expect(page.getByText('No se repetirá automáticamente.', { exact: false })).toBeVisible();
    await page.screenshot({ path: 'test-results/aprobacion-incierta.png', fullPage: true });
    await page.getByLabel('Evidencia de comprobación').fill('Comprobación ficticia del destino: acción presente con identificador de prueba.');
    await page.getByRole('button', { name: 'Confirmé que se ejecutó', exact: true }).click();
    await expect(page.getByText('No se repetirá automáticamente.', { exact: false })).toHaveCount(0);
    expect(await effects()).toBe(baseline + 1);
    const cursor = (await state()).schedule.cursor;
    await request.post('/api/test/mail', { data: { error: true, messages: [] } });
    await request.post('/api/review', { data: {} });
    await expect.poll(async () => (await state()).schedule.error).toContain('Fallo ficticio');
    expect((await state()).schedule.cursor).toBe(cursor);
    await request.post('/api/test/mail', { data: { error: false, messages: [] } });
    const blocked = await request.post('/api/agents/' + agent.id + '/messages', { headers: { Origin: 'https://sitio-ajeno.invalid' }, data: { text: 'hola' } });
    expect(blocked.status()).toBe(403);
});
