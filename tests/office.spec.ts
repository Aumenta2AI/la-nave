import { test, expect } from '@playwright/test';
test('Oficina, sesión, perfiles, solicitudes, aprobaciones y correo sin duplicados', async ({ page, request }) => {
    await page.goto('/');
    await expect(page.getByRole('heading', { name: 'Tu equipo, a la vista.' })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Pulpo, inicio' })).toBeVisible();
    await page.screenshot({ path: 'test-results/oficina.png', fullPage: true });
    await page.getByTestId('station-administrativo').dblclick();
    await expect(page.getByRole('dialog', { name: 'Conversación con Administrativo' })).toBeVisible();
    const send = async (text: string) => { await page.getByRole('textbox', { name: 'Mensaje', exact: true }).fill(text); await page.getByRole('button', { name: 'Enviar ↑' }).click(); };
    await send('hola');
    await expect(page.getByText('[SIMULADO] Sesión iniciada. hola', { exact: true })).toBeVisible();
    const s1 = await (await request.get('/api/state')).json();
    const session = s1.agents.find((a: any) => a.id === 'administrativo').sessionId;
    expect(session).toBeTruthy();
    await page.getByLabel('Esfuerzo de razonamiento').selectOption('high');
    await send('segundo mensaje');
    await expect(page.getByText('[SIMULADO] Sesión continuada. segundo mensaje', { exact: true })).toBeVisible();
    const s2 = await (await request.get('/api/state')).json();
    expect(s2.agents.find((a: any) => a.id === 'administrativo')).toMatchObject({ sessionId: session, effort: 'high' });
    await send('dos preguntas');
    await expect(page.getByRole('heading', { name: 'Primera pregunta' })).toBeVisible();
    await page.getByRole('button', { name: 'Cerrar conversación' }).click();
    await expect(page.getByTestId('station-administrativo')).not.toHaveAttribute('data-pending', '0');
    await page.reload();
    await expect(page.getByTestId('station-administrativo')).not.toHaveAttribute('data-pending', '0');
    await page.getByTestId('station-administrativo').focus();
    await page.keyboard.press('Enter');
    await page.getByRole('button', { name: 'Abrir conversación', exact: false }).click();
    await expect(page.getByRole('heading', { name: 'Primera pregunta' })).toBeVisible();
    let s = await (await request.get('/api/state')).json();
    let pending = s.requests.filter((r: any) => r.status === 'pending');
    await request.post('/api/requests/' + pending[0].id + '/decision', { data: { decision: 'answer', response: 'Respuesta uno' } });
    await page.getByRole('button', { name: 'Cerrar conversación' }).click();
    await expect(page.getByTestId('station-administrativo')).not.toHaveAttribute('data-pending', '0');
    await request.post('/api/requests/' + pending[1].id + '/decision', { data: { decision: 'reject' } });
    await expect(page.getByTestId('station-administrativo')).toHaveAttribute('data-pending', '0');
    await page.getByTestId('pulpo-avatar').click();
    await send('dos preguntas');
    await expect(page.getByRole('heading', { name: 'Primera pregunta' })).toBeVisible();
    await page.getByRole('button', { name: 'Cerrar conversación' }).click();
    await expect(page.getByTestId('pulpo-avatar')).toHaveAttribute('src', /mano-levantada/);
    s = await (await request.get('/api/state')).json();
    pending = s.requests.filter((r: any) => r.agentId === 'pulpo' && r.status === 'pending');
    for (const r of pending)
        await request.post('/api/requests/' + r.id + '/decision', { data: { decision: 'reject' } });
    await expect(page.getByTestId('pulpo-avatar')).toHaveAttribute('src', /normal/);
    await page.getByRole('button', { name: 'Añadir agente' }).click();
    await page.getByLabel('Nombre', { exact: true }).fill('Investigación');
    await page.getByLabel('Objetivo', { exact: true }).fill('Preparar informes');
    await page.getByLabel('Especialidad', { exact: true }).fill('Investigación de mercados');
    await page.getByRole('button', { name: 'Crear agente' }).click();
    await expect(page.getByRole('button', { name: 'Abrir chat de Investigación' })).toBeVisible();
    await page.getByTestId('station-administrativo').dblclick();
    await send('prepara correo');
    await expect(page.getByRole('button', { name: 'Aprobar', exact: true })).toBeVisible();
    expect(await (await request.get('/api/test/effects')).json()).toHaveLength(0);
    s = await (await request.get('/api/state')).json();
    const external = s.requests.find((r: any) => r.status === 'pending' && r.type === 'external');
    const replies = await Promise.all([request.post('/api/requests/' + external.id + '/decision', { data: { decision: 'approve' } }), request.post('/api/requests/' + external.id + '/decision', { data: { decision: 'approve' } })]);
    expect(replies.every(r => r.ok())).toBeTruthy();
    await expect.poll(async () => (await (await request.get('/api/test/effects')).json()).length).toBe(1);
    await send('prepara correo');
    await expect(page.getByRole('button', { name: 'Rechazar', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Rechazar', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Rechazar', exact: true })).toHaveCount(0);
    expect(await (await request.get('/api/test/effects')).json()).toHaveLength(1);
    await page.getByRole('button', { name: 'Cerrar conversación' }).click();
    await page.getByTestId('pulpo-avatar').click();
    await send('Revisa mi correo cada 30 minutos');
    await expect.poll(async () => (await (await request.get('/api/state')).json()).schedule.enabled).toBe(true);
    await page.getByRole('button', { name: 'Cerrar conversación' }).click();
    await request.post('/api/test/mail', { data: { messages: [{ id: 'mail-contract', subject: 'Revisar contrato de servicios', body: 'Analiza este contrato ficticio', source: 'ficticio:contrato' }, { id: 'mail-other', subject: 'Organizar una celebración', body: 'Necesito organizar esto', source: 'ficticio:gestion' }] } });
    await request.post('/api/review', { data: {} });
    await expect.poll(async () => (await (await request.get('/api/state')).json()).tasks.length).toBe(2);
    await request.post('/api/review', { data: {} });
    await page.waitForTimeout(1500);
    s = await (await request.get('/api/state')).json();
    expect(s.tasks).toHaveLength(2);
    expect(s.tasks.find((t: any) => t.mailId === 'mail-contract').agentId).toBe('legal');
    expect(s.tasks.find((t: any) => t.mailId === 'mail-other').agentId).toBe('administrativo');
    expect(s.agents.filter((a: any) => a.fallback)).toHaveLength(1);
    await page.reload();
    expect((await (await request.get('/api/state')).json()).agents.find((a: any) => a.id === 'administrativo').sessionId).toBe(session);
    await page.screenshot({ path: 'test-results/oficina-equipo.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.reload();
    await expect(page.getByRole('button', { name: 'Seleccionar puesto de Administrativo', exact: true })).toBeVisible();
    await page.screenshot({ path: 'test-results/movil.png', fullPage: true });
});
